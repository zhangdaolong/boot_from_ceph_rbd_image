#!/usr/bin/env bash
# Build an OVMF firmware that includes the UEFI network stack (TCP4/SNP/MNP).
# The distribution OVMF_CODE.fd on Debian/Ubuntu omits NetworkPkg, so the
# CephRbdDxe driver cannot find EFI_TCP4_PROTOCOL. This script builds a full
# OvmfPkgX64 firmware from the local EDK II tree with networking enabled.
set -euo pipefail

DEFAULT_EDK2="/home/ldzh/edk2-work/edk2"
ISOLATED_TOOLS="${UEFI_TOOLS_BIN:-/home/ldzh/edk2-work/tools/root/usr/bin}"

# /tmp is a small tmpfs in this environment; gcc needs a real temp dir.
export TMPDIR="${TMPDIR:-/home/ldzh/edk2-work/tmp}"
mkdir -p "$TMPDIR"

EDK2_WORKSPACE="${1:-${EDK2_WORKSPACE:-$DEFAULT_EDK2}}"

if [ ! -f "$EDK2_WORKSPACE/edksetup.sh" ]; then
  echo "ERROR: EDK II workspace not found: $EDK2_WORKSPACE" >&2
  exit 2
fi

# nasm/iasl are not installed system-wide; use the locally unpacked debs.
if [ -d "$ISOLATED_TOOLS" ]; then
  export PATH="$ISOLATED_TOOLS:$PATH"
fi

export WORKSPACE="$EDK2_WORKSPACE"
export EDK_TOOLS_PATH="$EDK2_WORKSPACE/BaseTools"
# OvmfPkg only needs packages inside the EDK II tree itself.
export PACKAGES_PATH="$EDK2_WORKSPACE"

cd "$EDK2_WORKSPACE"

# A sparse clone may not have Conf/ yet; seed it from BaseTools templates.
if [ ! -d "$EDK2_WORKSPACE/Conf" ]; then
  mkdir -p "$EDK2_WORKSPACE/Conf"
  for t in target tools_def build_rule; do
    [ -f "$EDK2_WORKSPACE/Conf/$t.txt" ] || \
      cp "$EDK2_WORKSPACE/BaseTools/Conf/$t.template" "$EDK2_WORKSPACE/Conf/$t.txt"
  done
fi

# Recent EDK II renamed GCC5 to GCC; synthesize a GCC5 alias for -t GCC5.
TOOLS_DEF="$EDK2_WORKSPACE/Conf/tools_def.txt"
if ! grep -q '^\*_GCC5_X64_CC_PATH' "$TOOLS_DEF"; then
  {
    echo ""
    echo "# GCC5 compatibility alias generated by build-ovmf-network.sh"
    grep -E '^[[:space:]]*(\*_GCC_|(DEBUG|RELEASE|NOOPT)_GCC_)' \
      "$EDK2_WORKSPACE/BaseTools/Conf/tools_def.template" | \
      sed -E -e 's/^([[:space:]]*\*_)GCC_/\1GCC5_/' \
             -e 's/^([[:space:]]*(DEBUG|RELEASE|NOOPT)_)GCC_/\1GCC5_/' \
             -e 's/ -flto -DUSING_LTO//g' \
             -e 's/ -flto//g' \
             -e '/_CC_FLAGS/ s/$/ -Wno-error=maybe-uninitialized/'
  } >> "$TOOLS_DEF"
elif ! grep -q '^\*_GCC5_X64_CC_FLAGS.*-Wno-error=maybe-uninitialized' "$TOOLS_DEF"; then
  # Existing alias from an earlier build: ensure the GCC14 warning workaround.
  sed -i -E '/^[[:space:]]*(DEBUG|RELEASE|NOOPT)_GCC5_X64_CC_FLAGS/ s/$/ -Wno-error=maybe-uninitialized/' "$TOOLS_DEF"
fi

# edksetup.sh reads variables before defining them, so relax `set -u` here.
set +u
# shellcheck source=/dev/null
. ./edksetup.sh
set -u

# BaseTools C binaries (GenFw/GenFfs/...) must exist to produce the firmware.
if [ ! -x "$EDK2_WORKSPACE/BaseTools/Source/C/bin/GenFw" ]; then
  echo "BaseTools binaries missing; building BaseTools..."
  if [ ! -f "$EDK2_WORKSPACE/BaseTools/Source/C/BrotliCompress/brotli/c/common/constants.h" ]; then
    git -C "$EDK2_WORKSPACE" submodule update --init --depth 1 \
      BaseTools/Source/C/BrotliCompress/brotli
  fi
  make -C "$EDK2_WORKSPACE/BaseTools" -j"$(nproc)"
fi

for tool in nasm iasl; do
  if command -v "$tool" >/dev/null 2>&1; then
    echo "$tool: $(command -v "$tool")"
  else
    echo "WARNING: $tool not found; install it or set UEFI_TOOLS_BIN." >&2
  fi
done

echo "WORKSPACE=$WORKSPACE"
echo "Building OvmfPkgX64 with network stack (NETWORK_ENABLE=TRUE, NETWORK_IP4_ENABLE=TRUE) ..."
build -p OvmfPkg/OvmfPkgX64.dsc -a X64 -b DEBUG -t GCC5 \
  -D NETWORK_ENABLE=TRUE \
  -D NETWORK_IP4_ENABLE=TRUE \
  -D NETWORK_IP6_ENABLE=FALSE \
  -D NETWORK_TLS_ENABLE=FALSE \
  -D NETWORK_HTTP_BOOT_ENABLE=FALSE \
  -D NETWORK_SNP_ENABLE=TRUE \
  -D CC_MEASUREMENT_ENABLE=FALSE \
  -D TPM2_ENABLE=FALSE

FV_DIR="$EDK2_WORKSPACE/Build/OvmfX64/DEBUG_GCC5/FV"
CODE="$FV_DIR/OVMF_CODE.fd"
VARS="$FV_DIR/OVMF_VARS.fd"
if [ -f "$CODE" ] && [ -f "$VARS" ]; then
  echo "BUILD OK:"
  echo "  CODE: $CODE"
  echo "  VARS: $VARS"
else
  echo "BUILD FAILED: expected OVMF_CODE.fd / OVMF_VARS.fd not found in $FV_DIR" >&2
  exit 1
fi
