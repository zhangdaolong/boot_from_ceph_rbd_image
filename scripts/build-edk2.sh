#!/usr/bin/env bash
# Build CephRbdDxe with a real EDK II/OVMF toolchain.
#
# Defaults to the local sparse EDK II clone at /home/ldzh/edk2-work/edk2.
# Override with EDK2_WORKSPACE (or the first positional argument).
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEFAULT_EDK2="/home/ldzh/edk2-work/edk2"
ISOLATED_TOOLS="${UEFI_TOOLS_BIN:-/home/ldzh/edk2-work/tools/root/usr/bin}"

# /tmp is only a 10 MB tmpfs in this environment; gcc needs a real temp dir.
export TMPDIR="${TMPDIR:-/home/ldzh/edk2-work/tmp}"
mkdir -p "$TMPDIR"

EDK2_WORKSPACE="${1:-${EDK2_WORKSPACE:-$DEFAULT_EDK2}}"
CEPH_PACKAGES="${2:-${CEPH_PACKAGES_PATH:-$PROJECT_ROOT/uefi-edk2}}"

if [ ! -f "$EDK2_WORKSPACE/edksetup.sh" ]; then
  echo "ERROR: EDK II workspace not found: $EDK2_WORKSPACE" >&2
  echo "Set EDK2_WORKSPACE to a directory containing edksetup.sh." >&2
  exit 2
fi

# nasm/iasl are not installed system-wide here; use the locally unpacked debs.
if [ -d "$ISOLATED_TOOLS" ]; then
  export PATH="$ISOLATED_TOOLS:$PATH"
fi

# WORKAROUND: CephRbdPkg.dec currently writes gCephRbdConfigGuid in
# hyphenated form, which EDK II rejects in a .dec (it requires C struct
# format). Keep the repository file untouched: generate a corrected overlay
# .dec ahead of the real package in PACKAGES_PATH.
DEC_OVERLAY="$TMPDIR/ceph-dec-overlay"
mkdir -p "$DEC_OVERLAY/CephRbdPkg"
sed -E 's#^([[:space:]]*gCephRbdConfigGuid[[:space:]]*=[[:space:]]*)9E5F1A2B-3C4D-4E5F-8A9B-0C1D2E3F4A5B#\1{0x9E5F1A2B, 0x3C4D, 0x4E5F, {0x8A, 0x9B, 0x0C, 0x1D, 0x2E, 0x3F, 0x4A, 0x5B}}#' \
  "$CEPH_PACKAGES/CephRbdPkg/CephRbdPkg.dec" > "$DEC_OVERLAY/CephRbdPkg/CephRbdPkg.dec"

# PACKAGES_PATH: corrected DEC overlay, this repository's packages, then EDK II.
if [ -n "${PACKAGES_PATH:-}" ]; then
  echo "Using PACKAGES_PATH override: $PACKAGES_PATH"
else
  export PACKAGES_PATH="$DEC_OVERLAY:$CEPH_PACKAGES:$EDK2_WORKSPACE"
fi
export WORKSPACE="$EDK2_WORKSPACE"
export EDK_TOOLS_PATH="$EDK2_WORKSPACE/BaseTools"

cd "$EDK2_WORKSPACE"

# A sparse clone may not have Conf/ yet; seed it from BaseTools templates.
if [ ! -d "$EDK2_WORKSPACE/Conf" ]; then
  mkdir -p "$EDK2_WORKSPACE/Conf"
  for t in target tools_def build_rule; do
    [ -f "$EDK2_WORKSPACE/Conf/$t.txt" ] || \
      cp "$EDK2_WORKSPACE/BaseTools/Conf/$t.template" "$EDK2_WORKSPACE/Conf/$t.txt"
  done
fi

# Recent EDK II removed the GCC5 toolchain tag (renamed it to GCC). The task
# requires -t GCC5, so synthesize a GCC5 alias from the GCC definitions.
TOOLS_DEF="$EDK2_WORKSPACE/Conf/tools_def.txt"
if ! grep -q '^\*_GCC5_X64_CC_PATH' "$TOOLS_DEF"; then
  {
    echo ""
    echo "# GCC5 compatibility alias generated by build-edk2.sh"
    grep -E '^[[:space:]]*(\*_GCC_|(DEBUG|RELEASE|NOOPT)_GCC_)' \
      "$EDK2_WORKSPACE/BaseTools/Conf/tools_def.template" | \
      sed -E -e 's/^([[:space:]]*\*_)GCC_/\1GCC5_/' \
             -e 's/^([[:space:]]*(DEBUG|RELEASE|NOOPT)_)GCC_/\1GCC5_/'
  } >> "$TOOLS_DEF"
fi

# edksetup.sh reads variables before defining them, so relax `set -u` here.
set +u
# shellcheck source=/dev/null
. ./edksetup.sh
set -u

# BaseTools C binaries (GenFw/GenFfs/...) must exist to produce the .efi.
if [ ! -x "$EDK2_WORKSPACE/BaseTools/Source/C/bin/GenFw" ]; then
  echo "BaseTools binaries missing; building BaseTools..."
  if [ ! -f "$EDK2_WORKSPACE/BaseTools/Source/C/BrotliCompress/brotli/c/common/constants.h" ]; then
    echo "Initializing required Brotli submodule..."
    git -C "$EDK2_WORKSPACE" submodule update --init --depth 1 \
      BaseTools/Source/C/BrotliCompress/brotli
  fi
  make -C "$EDK2_WORKSPACE/BaseTools" -j"$(nproc)"
fi

for tool in nasm iasl; do
  if command -v "$tool" >/dev/null 2>&1; then
    echo "$tool: $(command -v "$tool")"
  else
    echo "WARNING: $tool not found; install it or set UEFI_TOOLS_BIN." >&2
  fi
done

echo "WORKSPACE=$WORKSPACE"
echo "PACKAGES_PATH=$PACKAGES_PATH"
echo "Building CephRbdPkg/CephRbdDxe ..."
build -p CephRbdPkg/CephRbdPkg.dsc -a X64 -b DEBUG -t GCC5

EFI="$EDK2_WORKSPACE/Build/CephRbdPkg/DEBUG_GCC5/X64/CephRbdDxe.efi"
if [ -f "$EFI" ]; then
  echo "BUILD OK: $EFI"
else
  echo "BUILD FAILED: expected output not found: $EFI" >&2
  exit 1
fi
